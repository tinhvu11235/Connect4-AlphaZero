"""PyTorch equivalent of Chapter 15's position-value training cells.

The source dataset is generated by earlier Chapter 15 self-play and is absent
from this repository snapshot. This script fails clearly when that artifact is
not supplied; it never fabricates replacement examples.
"""

from __future__ import annotations

import argparse
from datetime import datetime
import json
from pathlib import Path
import pickle
import random
import sys
from time import perf_counter

import numpy as np
import torch
from torch.nn import functional as F
from torch.utils.data import DataLoader, TensorDataset

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from connect4_ai.models.position_net import PositionEvalNet, board_to_tensor
from connect4_ai.utils.device import resolve_device


def seed_everything(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def load_chapter15_dataset(path: Path) -> tuple[torch.Tensor, torch.Tensor]:
    if not path.exists():
        raise FileNotFoundError(
            f"Chapter 15 generated dataset is missing: {path}. Recreate it by "
            "running the original policy-gradient self-play/data-generation "
            "methodology before training; do not substitute fabricated data."
        )
    with path.open("rb") as stream:
        histories, outcomes = pickle.load(stream)

    boards: list[np.ndarray] = []
    labels: list[int] = []
    class_for_outcome = {0: 0, 1: 1, -1: 2}
    for states, outcome in zip(histories, outcomes):
        class_index = class_for_outcome[int(outcome)]
        for state in states:
            boards.append(np.asarray(state))
            labels.append(class_index)

    board_array = np.asarray(boards).reshape(-1, 7, 6)
    inputs = board_to_tensor(board_array)
    targets = torch.tensor(labels, dtype=torch.long)
    return inputs, targets


def train(args: argparse.Namespace) -> list[dict[str, float | int | None]]:
    seed_everything(args.seed)
    device = resolve_device(allow_cpu=args.allow_cpu)
    inputs, targets = load_chapter15_dataset(args.dataset)
    dataset = TensorDataset(inputs, targets)
    generator = torch.Generator().manual_seed(args.seed)
    loader = DataLoader(
        dataset,
        batch_size=args.batch_size,
        shuffle=True,
        generator=generator,
        num_workers=args.num_workers,
        pin_memory=device.type == "cuda",
    )

    model = PositionEvalNet().to(device)
    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=args.learning_rate,
        betas=(0.9, 0.999),
        eps=1e-7,
    )
    history: list[dict[str, float | int | None]] = []

    for epoch in range(1, args.epochs + 1):
        model.train()
        started = perf_counter()
        loss_sum = 0.0
        correct = 0
        seen = 0
        for batch_inputs, batch_targets in loader:
            batch_inputs = batch_inputs.to(device, non_blocking=True)
            batch_targets = batch_targets.to(device, non_blocking=True)
            optimizer.zero_grad(set_to_none=True)
            logits = model.forward_logits(batch_inputs)
            loss = F.cross_entropy(logits, batch_targets)
            loss.backward()
            optimizer.step()

            batch_count = batch_targets.shape[0]
            loss_sum += float(loss.detach().item()) * batch_count
            correct += int((logits.argmax(dim=1) == batch_targets).sum().item())
            seen += batch_count
        if device.type == "cuda":
            torch.cuda.synchronize(device)
        elapsed = perf_counter() - started
        history.append(
            {
                "epoch": epoch,
                "train_loss": loss_sum / seen,
                "train_accuracy": correct / seen,
                "validation_loss": None,
                "validation_accuracy": None,
                "samples_per_second": seen / elapsed,
                "epoch_seconds": elapsed,
            }
        )

    checkpoint = {
        "format_version": 1,
        "model_name": "PositionEvalNet",
        "model_state_dict": model.state_dict(),
        "optimizer_state_dict": optimizer.state_dict(),
        "epoch": args.epochs,
        "config": {
            "epochs": args.epochs,
            "batch_size": args.batch_size,
            "learning_rate": args.learning_rate,
            "dataset": str(args.dataset),
            "train_test_split": None,
            "validation_split": None,
        },
        "seed": args.seed,
        "training_metadata": {
            "timestamp": datetime.now().astimezone().isoformat(),
            "device": str(device),
            "torch_version": torch.__version__,
            "samples": len(dataset),
            "history": history,
            "note": (
                "No validation split: the original Chapter 15 fit call trained "
                "on all generated examples without validation."
            ),
        },
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    torch.save(checkpoint, args.output)
    args.metrics_output.parent.mkdir(parents=True, exist_ok=True)
    args.metrics_output.write_text(json.dumps(history, indent=2) + "\n")
    return history


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--dataset",
        type=Path,
        default=Path("archive/book/artifacts/files/PG_games_conn.p"),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("checkpoints/pretrained/position_eval.pt"),
    )
    parser.add_argument(
        "--metrics-output",
        type=Path,
        default=Path("results/position_eval_training_metrics.json"),
    )
    parser.add_argument("--epochs", type=int, default=100)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--learning-rate", type=float, default=0.0005)
    parser.add_argument("--num-workers", type=int, default=0)
    parser.add_argument("--seed", type=int, default=20260922)
    parser.add_argument("--allow-cpu", action="store_true")
    args = parser.parse_args()
    train(args)


if __name__ == "__main__":
    main()
